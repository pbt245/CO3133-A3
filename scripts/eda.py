#!/usr/bin/env python
"""EDA for the multimodal task (spec 6.10, proposal 2.5): pair counts, pair quality, missing-modality rates,
image and text distributions, duplicates, site names, a printed batch. Runs where the mirror is mounted
(Kaggle prepare notebook); needs the split / meta files of scripts/prepare_data.py and the DistilBERT tokenizer.

  python scripts/eda.py --split-dir /kaggle/working/prepare/data/splits --meta-dir /kaggle/working/prepare/data/meta \
                        --out /kaggle/working/prepare/eda

Outputs: eda_summary.json, EDA.md (tables used by the report), *.png, tfidf_top_terms.csv, per_class.csv, sites.csv.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd
from PIL import Image

from src.data.text import clean_title
from src.data.upmc import image_file, load_tokenizer, read_titles
from src.utils import paths
from src.utils.config import apply_overrides, load_config
from src.utils.io import load_json, resolve_path, save_json
from src.viz.plots import _save, plot_image_grid, plt


def describe(x) -> dict:
    x = pd.Series(x).astype(float)
    q = x.quantile([0, 0.01, 0.05, 0.25, 0.5, 0.75, 0.95, 0.99, 1]).tolist()
    return {"mean": float(x.mean()), **{f"p{p}": float(v) for p, v in zip((0, 1, 5, 25, 50, 75, 95, 99, 100), q)}}


def md_table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def pct(x) -> str:
    return f"{100 * x:.1f} %"


def hist(ax, data, bins, title, xlabel, logy=False, labels=None):
    for d, lab in zip(data, labels or [None] * len(data)):
        ax.hist(d, bins=bins, alpha=0.6, label=lab)
    ax.set_title(title, fontsize=10)
    ax.set_xlabel(xlabel)
    if logy:
        ax.set_yscale("log")
    if labels:
        ax.legend(fontsize=8)
    ax.grid(alpha=0.3)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--split-dir", default="data/splits")
    p.add_argument("--meta-dir", default="data/meta")
    p.add_argument("--out", default="outputs/eda")
    p.add_argument("--upmc-root", default="auto")
    p.add_argument("--config", default="configs/upmc/f1_concat.yaml", help="for the printed batch")
    p.add_argument("--seed", type=int, default=42)
    args = p.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    split_dir, meta_dir = resolve_path(args.split_dir), resolve_path(args.meta_dir)
    info = load_json(split_dir / "split.json")
    classes = info["classes"]
    sp = pd.concat([pd.read_csv(split_dir / f"{s}.csv", dtype={"id": str}).assign(split=s) for s in ("train", "val", "test")])
    im = pd.read_csv(meta_dir / "image_meta.csv.gz", dtype={"id": str})
    tx = pd.read_csv(meta_dir / "text_meta.csv.gz", dtype={"id": str}, keep_default_na=False)
    df = sp.merge(im.drop(columns=["label", "official_split", "has_img", "cluster_id", "test_dup", "cross_label"]), on="id") \
           .merge(tx.drop(columns=["label", "official_split", "has_txt"]), on="id")
    root = paths.upmc_root(args.upmc_root)
    titles = read_titles(root).set_index("id")["title"].map(clean_title)
    df["title"] = df["id"].map(titles).fillna("")
    df["complete"] = df["has_img"].astype(bool) & df["has_txt"].astype(bool)
    S, md = {}, ["# EDA - UPMC Food-101 image-title pairs", "",
                 "Generated by `scripts/eda.py` from the committed split / meta files and the Kaggle mirror.", ""]
    rng = np.random.default_rng(args.seed)

    # ---- 1. pair counts and missing modality
    rows = []
    for s in ("train", "val", "test"):
        c = info["counts"][s]
        rows.append([s, f"{c['items']:,}", f"{c['complete']:,}", f"{c['text_missing']:,} ({pct(c['text_missing'] / c['items'])})",
                     c["image_missing"], c["both_missing"], f"{c['test_dup']:,}", f"{c['cross_label']:,}"])
    md += ["## 1. Pair counts and missing modalities", "",
           md_table(["split", "items", "complete pairs", "text-missing", "image-missing", "both missing",
                     "test dup of train", "in cross-label cluster"], rows), ""]
    S["counts"] = info["counts"]
    S["pairing"] = info["pairing"]
    md += [f"Pairing: {info['pairing']}", ""]
    pc = df.groupby(["split", "label"]).agg(items=("id", "size"), complete=("complete", "sum"),
                                            text_missing=("has_txt", lambda x: int((~x.astype(bool)).sum())))
    pc = pc.unstack(0)
    pc.columns = [f"{a}_{b}" for a, b in pc.columns]
    tm = df[df["split"] == "train"].groupby("label")["has_txt"].apply(lambda x: 1 - x.astype(bool).mean())
    md += ["Train classes with the highest text-missing rate: " +
           ", ".join(f"{c} {pct(v)}" for c, v in tm.sort_values(ascending=False).head(8).items()), ""]
    fig, ax = plt.subplots(figsize=(22, 4.5))
    x = np.arange(len(classes))
    for k, s in enumerate(("train", "val", "test")):
        cnt = df[(df["split"] == s) & df["complete"]].groupby("label").size().reindex(classes, fill_value=0)
        ax.bar(x + (k - 1) * 0.27, cnt.to_numpy(), 0.27, label=f"{s} (n={int(cnt.sum()):,})")
    ax.set_xticks(x)
    ax.set_xticklabels(classes, rotation=90, fontsize=6)
    ax.set_ylabel("complete pairs")
    ax.legend()
    ax.grid(axis="y", alpha=0.3)
    ax.set_title("Complete pairs per class and split")
    _save(fig, out / "class_distribution.png")
    cc = df[(df["split"] == "train") & df["complete"]].groupby("label").size()
    S["train_complete_per_class"] = {"min": int(cc.min()), "max": int(cc.max()), "ratio": float(cc.max() / cc.min())}

    # ---- 2. pair quality: class-name mentions, keyword rule
    rows = []
    S["mentions"] = {}
    for s in ("train", "val", "test"):
        d = df[(df["split"] == s) & df["complete"]]
        k0 = (d["k0_pred"] == d["label"]).mean()
        r = {"exact_name": float(d["mention_true_exact"].astype(bool).mean()),
             "lexicon": float(d["mention_true"].astype(bool).mean()),
             "other_class": float(d["mention_other"].astype(bool).mean()),
             "other_not_true": float((d["mention_other"].astype(bool) & ~d["mention_true"].astype(bool)).mean()),
             "no_class": float((d["n_classes_mentioned"] == 0).mean()),
             "k0_accuracy_complete": float(k0)}
        S["mentions"][s] = r
        rows.append([s, pct(r["exact_name"]), pct(r["lexicon"]), pct(r["other_class"]), pct(r["other_not_true"]),
                     pct(r["no_class"]), pct(r["k0_accuracy_complete"])])
    md += ["## 2. Pair quality: label information in the title (complete pairs)", "",
           md_table(["split", "own class, exact name", "own class, lexicon", "another class", "another class only",
                     "no class mentioned", "keyword rule K0 acc."], rows), "",
           "The lexicon adds singular/plural forms and hand-written synonyms (`src/data/text.py`).", ""]
    per_class = df[(df["split"] == "train") & df["complete"]].groupby("label").agg(
        mention_true=("mention_true", "mean"), mention_other=("mention_other", "mean"),
        k0_acc=("k0_pred", lambda s: 0.0)).reindex(classes)
    k0c = df[(df["split"] == "train") & df["complete"]]
    per_class["k0_acc"] = (k0c["k0_pred"] == k0c["label"]).groupby(k0c["label"]).mean().reindex(classes)
    per_class = per_class.join(pc).join(tm.rename("train_text_missing_rate"))
    per_class.to_csv(out / "per_class.csv")
    srt = per_class["mention_true"].sort_values()
    md += ["Lowest own-name mention (train): " + ", ".join(f"{c} {pct(v)}" for c, v in srt.head(8).items()),
           "", "Highest: " + ", ".join(f"{c} {pct(v)}" for c, v in srt.tail(5).items()), ""]
    fig, ax = plt.subplots(figsize=(22, 4))
    ax.bar(range(len(srt)), srt.to_numpy(), color="tab:blue")
    ax.set_xticks(range(len(srt)))
    ax.set_xticklabels(srt.index, rotation=90, fontsize=6)
    ax.set_ylabel("share of train titles")
    ax.set_title("Titles that mention their own class (lexicon), per class")
    ax.grid(axis="y", alpha=0.3)
    _save(fig, out / "class_name_mention_per_class.png")

    # ---- 3. text distributions
    tok = load_tokenizer({"text": {"model_dir": "auto"}})
    has_title = df["has_title_row"].astype(bool)
    enc = tok(df.loc[has_title, "title"].tolist(), add_special_tokens=True, truncation=False)["input_ids"]
    df.loc[has_title, "n_tokens"] = [len(e) for e in enc]
    tr = df[(df["split"] == "train") & has_title]
    vocab = set(w for t in tr["title"].str.lower() for w in t.split())
    S["text"] = {"words": describe(tr["n_words"]), "chars": describe(tr["n_chars"]), "tokens": describe(tr["n_tokens"]),
                 "truncated_at_64": int((df["n_tokens"] > 64).sum()),
                 "truncated_share": float((df.loc[has_title, "n_tokens"] > 64).mean()),
                 "train_vocab_whitespace_lower": len(vocab),
                 "one_word_titles": {s: int(((df["split"] == s) & has_title & (df["n_words"] == 1)).sum())
                                     for s in ("train", "val", "test")}}
    md += ["## 3. Text distributions (titles with a row in the CSV)", "",
           md_table(["statistic (train)", "mean", "p5", "p50", "p95", "p99", "max"],
                    [[n, f"{d['mean']:.1f}", d["p5"], d["p50"], d["p95"], d["p99"], d["p100"]]
                     for n, d in (("words", S["text"]["words"]), ("characters", S["text"]["chars"]),
                                  ("DistilBERT tokens (incl. [CLS]/[SEP])", S["text"]["tokens"]))]), "",
           f"Titles longer than 64 tokens (truncated): {S['text']['truncated_at_64']} "
           f"({100 * S['text']['truncated_share']:.2f} %). Train vocabulary (lower-cased whitespace words): "
           f"{len(vocab):,}. One-word titles: {S['text']['one_word_titles']}.", ""]
    fig, axes = plt.subplots(1, 3, figsize=(15, 3.6))
    hist(axes[0], [tr["n_words"].clip(upper=40)], np.arange(0, 41), "Words per title (train, clipped at 40)", "words")
    hist(axes[1], [tr["n_tokens"].clip(upper=70)], np.arange(0, 71), "DistilBERT tokens per title", "tokens")
    axes[1].axvline(64, color="red", ls="--", lw=1)
    hist(axes[2], [tr["n_content_words"].clip(upper=20)], np.arange(0, 21), "Content words per title", "content words")
    _save(fig, out / "text_lengths.png")
    # failing criterion 2: what those titles look like
    bad = df[has_title & ~df["has_txt"].astype(bool) & (df["split"] == "train")]
    md += [f"Train titles failing the content-word criterion: {len(bad):,}. Most frequent:", "",
           md_table(["title", "count"], [[f"`{t[:60]}`", c] for t, c in bad["title"].value_counts().head(12).items()]), ""]

    # TF-IDF top terms per class (fit on train complete titles, one document per class)
    from sklearn.feature_extraction.text import TfidfVectorizer
    trc = df[(df["split"] == "train") & df["complete"]]
    docs = trc.groupby("label")["title"].apply(lambda s: " ".join(s)).reindex(classes).fillna("")
    vec = TfidfVectorizer(lowercase=True, ngram_range=(1, 1), min_df=1, sublinear_tf=True,
                          token_pattern=r"(?u)\b[a-zA-Z][a-zA-Z]+\b")
    X = vec.fit_transform(docs.tolist())
    terms = np.array(vec.get_feature_names_out())
    top = {c: list(terms[np.argsort(-X[i].toarray().ravel())[:10]]) for i, c in enumerate(classes)}
    pd.DataFrame({"class": classes, "top_terms": [" ".join(top[c]) for c in classes]}).to_csv(out / "tfidf_top_terms.csv",
                                                                                               index=False)
    show = list(rng.choice(classes, size=min(8, len(classes)), replace=False))
    md += ["TF-IDF top terms per class (train, one document per class), 8 random classes:", "",
           md_table(["class", "top terms"], [[c, ", ".join(top[c][:8])] for c in sorted(show)]), ""]

    # site names
    has_site = df["site"] != ""
    site_tr = df[(df["split"] == "train") & has_site & df["complete"]]
    sc = site_tr["site"].value_counts()
    big = sc[sc >= 50].index
    purity = site_tr[site_tr["site"].isin(big)].groupby("site")["label"].agg(lambda s: s.value_counts(normalize=True).iloc[0])
    nlab = site_tr[site_tr["site"].isin(big)].groupby("site")["label"].nunique()
    sites = pd.DataFrame({"train_items": sc}).join(purity.rename("majority_class_share")).join(nlab.rename("n_classes"))
    sites.to_csv(out / "sites.csv")
    w_purity = float((sites.dropna()["majority_class_share"] * sites.dropna()["train_items"]).sum()
                     / sites.dropna()["train_items"].sum()) if len(big) else float("nan")
    S["sites"] = {"share_with_site": {s: float(has_site[df["split"] == s].mean()) for s in ("train", "val", "test")},
                  "distinct_sites_train": int(len(sc)), "sites_with_50plus_items": int(len(big)),
                  "weighted_majority_class_share_50plus": w_purity}
    md += ["## 4. Site names inside titles", "",
           f"Titles with a trailing site segment: train {pct(S['sites']['share_with_site']['train'])}, "
           f"test {pct(S['sites']['share_with_site']['test'])}; {len(sc):,} distinct sites in train. For sites with "
           f">= 50 train items ({len(big)}), the majority class covers {pct(w_purity)} of their items on average "
           "(low = the site name says little about the class).", "",
           md_table(["site", "train items", "classes", "majority-class share"],
                    [[s, int(r.train_items), int(r.n_classes) if r.n_classes == r.n_classes else "",
                      pct(r.majority_class_share) if r.majority_class_share == r.majority_class_share else ""]
                     for s, r in sites.head(15).iterrows()]), ""]

    # ---- 5. image distributions
    ok = df[df["ok"].astype(bool)]
    tri = ok[ok["split"] == "train"]
    short = ok[["w", "h"]].min(axis=1)
    aspect = ok["w"] / ok["h"]
    n = tri["n_px"].sum()
    mean = [float(tri[f"sum_{c}"].sum() / n) for c in "rgb"]
    std = [float(np.sqrt(tri[f"sumsq_{c}"].sum() / n - m ** 2)) for c, m in zip("rgb", mean)]
    S["images"] = {"short_side": describe(short), "aspect_w_over_h": describe(aspect), "kbytes": describe(ok["nbytes"] / 1e3),
                   "train_channel_mean_256px": mean, "train_channel_std_256px": std,
                   "invalid": {"decode_fail": int((~df["ok"].astype(bool)).sum()),
                               "short_side_lt_64": int((df[["w", "h"]].min(axis=1) < 64).sum()),
                               "near_constant_std_le_2": int((df["std"] <= 2).sum())}}
    md += ["## 5. Image distributions", "",
           md_table(["statistic (all images)", "p1", "p50", "p99", "min", "max"],
                    [[n_, f"{d['p1']:.2f}", f"{d['p50']:.2f}", f"{d['p99']:.2f}", f"{d['p0']:.2f}", f"{d['p100']:.2f}"]
                     for n_, d in (("shorter side (px)", S["images"]["short_side"]),
                                   ("aspect ratio w/h", S["images"]["aspect_w_over_h"]),
                                   ("file size (kB)", S["images"]["kbytes"]))]), "",
           f"Train channel mean / std (pixels in [0, 1], after resizing to a shorter side of 256): "
           f"{[round(v, 3) for v in mean]} / {[round(v, 3) for v in std]} (ImageNet: [0.485, 0.456, 0.406] / "
           f"[0.229, 0.224, 0.225]). Invalid images: {S['images']['invalid']}.", ""]
    fig, axes = plt.subplots(1, 3, figsize=(15, 3.6))
    hist(axes[0], [short.clip(upper=1000)], 60, "Shorter side (px, clipped at 1000)", "px")
    hist(axes[1], [aspect.clip(0.3, 3)], 60, "Aspect ratio w/h (clipped to 0.3-3)", "w/h", logy=True)
    hist(axes[2], [(ok["nbytes"] / 1e3).clip(upper=600)], 60, "File size (kB, clipped at 600)", "kB")
    _save(fig, out / "image_stats.png")

    def thumb(r, size=224):
        with Image.open(image_file(root, r.official_split, r.label, r.id)) as img:
            img = img.convert("RGB")
            s = min(img.size)
            l, t = (img.size[0] - s) // 2, (img.size[1] - s) // 2
            return np.asarray(img.crop((l, t, l + s, t + s)).resize((size, size)))

    one = df[(df["split"] == "train") & df["complete"]].groupby("label").sample(1, random_state=args.seed).set_index("label").loc[classes]
    plot_image_grid([thumb(r, 128) for r in one.reset_index().itertuples()], list(classes), out / "samples_per_class.png",
                    ncols=13, cell=1.5, fontsize=5, suptitle="One random train image per class")
    rnd = df[(df["split"] == "train") & df["has_title_row"].astype(bool)].sample(20, random_state=args.seed)
    plot_image_grid([thumb(r) for r in rnd.itertuples()],
                    [f"{r.label}\n\"{r.title[:40]}\"" + ("" if r.has_txt else "\n[text-missing]") for r in rnd.itertuples()],
                    out / "samples_pairs.png", ncols=5, cell=2.8, fontsize=6, suptitle="Random train pairs (image + title)")

    # ---- 6. duplicates
    d = info["duplicates"]
    nt = df[has_title & (df["norm_md5"] != "")]
    rep = nt.groupby("norm_md5").agg(n=("id", "size"), splits=("official_split", "nunique"), labels=("label", "nunique"))
    rep = rep[rep["n"] > 1]
    S["duplicates"] = {**d, "repeated_titles": int(len(rep)), "items_with_repeated_title": int(rep["n"].sum()),
                       "repeated_titles_across_official_splits": int((rep["splits"] > 1).sum()),
                       "repeated_titles_across_labels": int((rep["labels"] > 1).sum())}
    sizes = df.drop_duplicates("cluster_id")["cluster_size"]
    md += ["## 6. Duplicates", "",
           md_table(["quantity", "value"], [
               ["md5 links / pHash pairs (<= %d bits)" % d["max_hamming"], f"{d['md5_edges']:,} / {d['phash_pairs']:,}"],
               ["clusters with >= 2 items (items)", f"{d['clusters_with_2plus_items']:,} ({d['items_in_2plus_clusters']:,})"],
               ["largest clusters", d["largest_clusters"]],
               ["cross-label clusters", f"{d['cross_label_clusters']:,}"],
               ["test items linked to official train (test_dup)", f"{info['counts']['test']['test_dup']:,}"],
               ["repeated normalised titles (items)", f"{len(rep):,} ({int(rep['n'].sum()):,})"],
               ["... across train/test / across labels", f"{int((rep['splits'] > 1).sum()):,} / {int((rep['labels'] > 1).sum()):,}"],
           ]), "", f"Cluster sizes: {sizes.value_counts().sort_index().head(10).to_dict()}", ""]
    big_c = df[df["cluster_size"] >= 2].sort_values(["cluster_size", "cluster_id"], ascending=False)
    if len(big_c):
        cid = big_c[big_c["cross_label"].astype(bool)]["cluster_id"].unique()[:4]
        ex = df[df["cluster_id"].isin(cid)].groupby("cluster_id").head(3)
        plot_image_grid([thumb(r, 160) for r in ex.itertuples()],
                        [f"{r.split} | {r.label}\n\"{r.title[:30]}\"" for r in ex.itertuples()],
                        out / "duplicates_cross_label.png", ncols=6, cell=2.2, fontsize=5,
                        suptitle="Cross-label duplicate clusters (same picture, different label)")

    # ---- 7. printed batch (exact model input)
    try:
        from torch.utils.data import default_collate
        from src.data.upmc import build_datasets
        cfg = apply_overrides(load_config(resolve_path(args.config)),
                              [f"data.split_dir={split_dir}", f"data.upmc_root={root}", f"data.image_root={root}"])
        ds, meta = build_datasets(cfg, sets=("val",))
        b = default_collate([ds["val"][i] for i in range(8)])
        lines = [f"{k}: {tuple(v.shape)} {v.dtype}" for k, v in b.items()]
        lines += [f"[{classes[int(b['label'][i])]}] {tok.decode(b['input_ids'][i][b['attention_mask'][i].bool()])}"
                  for i in range(4)]
        md += ["## 7. Example batch (F1 input, val, 8 items)", "", "```", *lines, "```", ""]
        S["batch_example"] = lines
    except Exception as e:  # noqa: BLE001
        md += ["## 7. Example batch", "", f"failed: {e}", ""]

    save_json(S, out / "eda_summary.json")
    (out / "EDA.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    print(f"-> {out}")


if __name__ == "__main__":
    main()
